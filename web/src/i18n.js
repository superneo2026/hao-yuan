import { reactive } from 'vue'

const STORAGE_KEY = 'hy.locale'
export const DEFAULT_LOCALE = 'zh-CN'

export const localeOptions = [
  { id: 'zh-CN', label: '简体中文', short: '中', htmlLang: 'zh-CN' },
  { id: 'zh-TW', label: '繁體中文', short: '繁', htmlLang: 'zh-TW' },
  { id: 'en', label: 'English', short: 'EN', htmlLang: 'en' }
]

export const i18n = reactive({
  locale: localStorage.getItem(STORAGE_KEY) || DEFAULT_LOCALE
})

function normalizeLocale(value) {
  return localeOptions.some((item) => item.id === value) ? value : DEFAULT_LOCALE
}

export function setLocale(id, persist = true) {
  const locale = normalizeLocale(id)
  i18n.locale = locale
  if (persist) localStorage.setItem(STORAGE_KEY, locale)
  document.documentElement.lang = locale
  document.title = t('app.title')
}

export function t(key, params = {}, fallback = null) {
  const table = messages[i18n.locale] || messages[DEFAULT_LOCALE]
  let value = table[key]
  if (value === undefined) value = messages[DEFAULT_LOCALE][key]
  if (value === undefined) return fallback === null ? key : fallback
  return value.replace(/\{(\w+)\}/g, (_, name) => (params[name] !== undefined ? params[name] : `{${name}}`))
}

export function te(key) {
  return messages[i18n.locale]?.[key] !== undefined || messages[DEFAULT_LOCALE][key] !== undefined
}

export function tr(key, fallback, params = {}) {
  return t(key, params, fallback)
}

