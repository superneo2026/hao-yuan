export function isDefaultSessionTitle(title) {
  return DEFAULT_SESSION_TITLES.has(String(title || '').trim())
}

export function summarizeSessionTitle(text) {
  let value = String(text || '').replace(/```[\s\S]*?```/g, ' ').replace(/\s+/g, ' ').trim()
  if (!value) return ''
  value = value.replace(/^(?:你好|您好|嗨|哈喽|hi|hello|hey)[，,。.!！?？\s]*/i, '')
  value = value.replace(/^(?:请|麻烦|帮我|帮忙|给我|please|can you|could you|help me)\s*/i, '')
  value = value.replace(/^[\s"'`“”‘’#*\-]+|[\s"'`“”‘’#*\-]+$/g, '').trim()
  if (!value) return ''
  const limit = /[\u4e00-\u9fff]/.test(value) ? 24 : 56
  return value.length > limit ? `${value.slice(0, limit).trimEnd()}…` : value
}

export function sessionTitle(session) {
  if (!session) return t('session.untitled')
  const raw = String(session.title || '').trim()
  if (raw && !isDefaultSessionTitle(raw)) return raw
  return summarizeSessionTitle(session.first_question || '') || t('session.untitled')
}

export function kindLabel(kind) {
  return t(`kind.${kind || 'auto'}`, {}, kind || 'auto')
}

export function statusLabel(status) {
  const map = {
    waiting_input: 'status.approval',
    cancelled: 'status.stopped',
    stale: 'status.stalled',
    ok: 'status.healthy'
  }
  return t(map[status] || `status.${status}`, {}, status)
}

export function pluginDescription(name, fallback) {
  return t(`plugin.desc.${name}`, {}, fallback || '')
}

export function skillTitle(skill) {
  if (!skill) return ''
  return t(`skill.${skill.name}.title`, {}, skill.title || skill.name)
}

export function skillDescription(skill) {
  if (!skill) return ''
  return t(`skill.${skill.name}.desc`, {}, skill.description || '')
}

export function formatRelativeTime(value) {
  if (!value) return ''
  const date = new Date(String(value).replace(' ', 'T'))
  if (Number.isNaN(date.getTime())) return ''
  const diff = Date.now() - date.getTime()
  if (diff < 60000) return t('time.now')
  if (diff < 3600000) return t('time.minutesShort', { n: Math.floor(diff / 60000) })
  if (diff < 86400000) return t('time.hoursShort', { n: Math.floor(diff / 3600000) })
  return `${date.getMonth() + 1}/${date.getDate()}`
}

